        var turn = Math.atan2(Math.sin(hour), Math.tan(lat) * Math.cos(body.dec) - Math.sin(body.dec) * Math.cos(hour));
        return { alt: alt / RAD, az: (az / RAD + 360) % 360, turn: turn };
