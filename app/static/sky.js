    function poly(coefficients, x) {
        var value = 0;
        for (var i = coefficients.length - 1; i >= 0; i--) value = value * x + coefficients[i];
        return value;
    }

    function cartesian(ra, dec, distance) {
        return [distance * Math.cos(dec) * Math.cos(ra), distance * Math.cos(dec) * Math.sin(ra), distance * Math.sin(dec)];
    }

    function spherical(v) {
        var distance = Math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
        return { ra: Math.atan2(v[1], v[0]), dec: Math.asin(v[2] / distance), distance: distance };
    }

    // A body as seen from the place rather than Earth's centre (km): it matters for the moon, an Earth's
    // radius nearer to some places than others, so a solar eclipse is seen in some places and not others
    function fromPlace(body, time, place) {
        var lat = place[0] * RAD, angle = sidereal(time, place);
        var c = 1 / Math.sqrt(1 + EARTH_FLATTENING * (EARTH_FLATTENING - 2) * Math.sin(lat) * Math.sin(lat));
        var s = (1 - EARTH_FLATTENING) * (1 - EARTH_FLATTENING) * c;
        var here = [EARTH_RADIUS * c * Math.cos(lat) * Math.cos(angle), EARTH_RADIUS * c * Math.cos(lat) * Math.sin(angle), EARTH_RADIUS * s * Math.sin(lat)];
        var v = cartesian(body.ra, body.dec, body.distance);
        return spherical([v[0] - here[0], v[1] - here[1], v[2] - here[2]]);
    }

    function separation(a, b) {
        var cos = Math.sin(a.dec) * Math.sin(b.dec) + Math.cos(a.dec) * Math.cos(b.dec) * Math.cos(a.ra - b.ra);
        return Math.acos(Math.max(-1, Math.min(1, cos)));
    }

    // How much of a disc of radius r is covered by one of radius cover, their centres d apart
    function covered(r, cover, d) {
        if (d >= r + cover) return 0;
        if (d <= Math.abs(r - cover)) return cover >= r ? 1 : (cover * cover) / (r * r);
        var area = r * r * Math.acos((d * d + r * r - cover * cover) / (2 * d * r)) + cover * cover * Math.acos((d * d + cover * cover - r * r) / (2 * d * cover))
            - 0.5 * Math.sqrt((-d + r + cover) * (d + r - cover) * (d - r + cover) * (d + r + cover));
        return area / (Math.PI * r * r);
    }

    // Where `other` is from `body` on the screen (x right, y down), in units of `size` (radians), with the
    // body's north turned `turn` (radians) clockwise from straight up. East is to the left of north.
    function offset(body, other, size, turn) {
        var dra = Math.atan2(Math.sin(other.ra - body.ra), Math.cos(other.ra - body.ra));
        var east = dra * Math.cos(body.dec), north = other.dec - body.dec;
        var x = -east / size, y = -north / size;
        return [x * Math.cos(turn) - y * Math.sin(turn), x * Math.sin(turn) + y * Math.cos(turn)];
    }

    // An eclipse seen from the place now, or null: { kind: "solar" or "lunar", type: "partial", "total" or
