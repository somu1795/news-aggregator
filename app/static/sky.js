    // The next rise and set of the sun or moon within a day: { rise, set } (times; either may be missing),
    // found in 10-minute steps, then narrowed to a second
    function riseSet(name, time, place) {
        var STEP = 600000, found = {}, before = isUp(name, time, place);
        for (var t = time + STEP; t <= time + 86400000; t += STEP) {
            var now = isUp(name, t, place);
            if (now !== before) {
                var low = t - STEP, high = t;
                while (high - low > 1000) {
                    var mid = (low + high) / 2;
                    if (isUp(name, mid, place) === before) low = mid; else high = mid;
                }
                found[now ? "rise" : "set"] = found[now ? "rise" : "set"] || high;
            }
            before = now;
        }
        return found;
    }

