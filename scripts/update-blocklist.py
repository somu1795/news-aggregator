#!/usr/bin/env python3
"""
Rebuilds the headless browsers' block list (smokescreen/filter/acl.yaml): ad
and tracker domains from Peter Lowe's list (pgl.yoyo.org), plus video-player
hosts. The filtered proxy (browser-egress-filtered) refuses them, so pages load
without their ads and videos; the summarizer retries a page that fails without
them through the unfiltered proxy, and remembers that site (see app/summarizer.py).

    scripts/update-blocklist.py && docker compose restart browser-egress-filtered
"""

import re
import sys
import urllib.request
from pathlib import Path

ACL = Path(__file__).resolve().parent.parent / "smokescreen" / "filter" / "acl.yaml"
LIST_URL = "https://pgl.yoyo.org/adservers/serverlist.php?hostformat=nohtml&showintro=0&mimetype=plaintext"
# Embedded players: news pages autoplay them, and they are the heaviest part of a page
VIDEO = [
    "anyclip.com", "aniview.com", "brightcove.com", "brightcove.net", "brightcovecdn.com", "connatix.com",
    "dailymotion.com", "dmcdn.net", "ex.co", "glomex.com", "googlevideo.com", "jwpcdn.com", "jwplayer.com",
    "jwpltx.com", "jwpsrv.com", "kaltura.com", "kaltura.net", "primis.tech", "spotx.tv", "springserve.com",
    "teads.tv", "vidazoo.com", "vimeo.com", "vimeocdn.com", "youtube-nocookie.com", "youtube.com", "ytimg.com",
]
DOMAIN = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")


def main():
    request = urllib.request.Request(LIST_URL, headers={"User-Agent": "news-aggregator-blocklist"})
    with urllib.request.urlopen(request, timeout=30) as response:
        listed = response.read().decode().split()
    domains = sorted({d.lower() for d in listed if DOMAIN.match(d.lower())} | set(VIDEO))
    if len(domains) < 1000:  # The list has ~3,500: anything far less is a broken download
        sys.exit(f"Only {len(domains)} domains downloaded; {ACL} left as it was")
    lines = ["# Generated by scripts/update-blocklist.py: don't edit by hand.",
             "# Each domain and its subdomains are refused by the filtered browser proxy.",
             "version: v1", "services: []", "default:", "  project: browser", "  action: open", "global_deny_list:"]
    lines += [f'  - "{glob}"' for d in domains for glob in (d, f"*.{d}")]
    ACL.write_text("\n".join(lines) + "\n")
    print(f"{len(domains)} domains written to {ACL}")


if __name__ == "__main__":
    main()
